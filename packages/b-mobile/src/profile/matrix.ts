// Renders every capability and every profile default per platform as one Markdown document
// (docs/PLATFORM-MATRIX.md). A test fails when the committed file is stale, so any change to what
// differs between platforms shows up as a diff in the PR that makes it (b-oss#633, b-oss#634).

import { capabilitiesTable } from '../platform/capabilities.js';
import type { PlatformKind } from '../platform/platformKind.js';
import { PROFILES, type ProfileKind } from './profile.js';

const PLATFORMS: PlatformKind[] = ['android', 'ios', 'desktop', 'web'];
const PROFILE_KINDS: ProfileKind[] = ['handheld', 'desktop'];

function flatten(value: unknown, prefix = ''): [string, string][] {
  if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
    const entries = Object.entries(value);
    if (entries.length === 0) return [[prefix, '{}']];
    return entries.flatMap(([key, child]) => flatten(child, prefix ? `${prefix}.${key}` : key));
  }
  return [[prefix, JSON.stringify(value)]];
}

function table(heading: string[], columns: Record<string, unknown>[]): string {
  const keys = flatten(columns[0]).map(([key]) => key);
  const cells = columns.map((column) => new Map(flatten(column)));
  const lines = [
    `| ${heading.join(' | ')} |`,
    `| ${heading.map(() => '---').join(' | ')} |`,
    ...keys.map((key) => `| \`${key}\` | ${cells.map((c) => `\`${c.get(key) ?? ''}\``).join(' | ')} |`),
  ];
  return lines.join('\n');
}

export function renderPlatformMatrix(): string {
  const capabilities = table(
    ['Capability', ...PLATFORMS],
    PLATFORMS.map((kind) => ({ ...capabilitiesTable(kind) })),
  );
  const defaults = table(
    ['Default', ...PROFILE_KINDS],
    PROFILE_KINDS.map((kind) => {
      const { prefs, grid, keyboardWheelZoom, nav } = PROFILES[kind];
      return { prefs, grid, keyboardWheelZoom, nav };
    }),
  );
  return `<!-- Generated by src/profile/matrix.ts. Do not edit by hand: run
\`UPDATE_PLATFORM_MATRIX=1 npx vitest run src/profile\` in packages/b-mobile to regenerate. -->

# Platform matrix

What differs between platforms, in one place (b-oss#633). Capabilities say what a platform can do;
profile defaults say what we choose. android, ios and web use the \`handheld\` profile, the desktop
shell uses \`desktop\`. \`ios\` values are design intent (there is no iOS project yet). \`web\` is
the production browser build (a dev server proxies the API like the desktop shell does).

## Capabilities

${capabilities}

## Profile defaults

The \`prefs\` rows are the defaults for the device preferences; the user's own changes are stored
on top as overrides.

${defaults}
`;
}
